-- =====================================================================
-- E-Shop 库存 Lua 加回（回滚预扣 / 取消回补共用）
-- KEYS[1] = stock:sku:{skuId}
-- ARGV[1] = 加回数量
-- 返回：
--   >= 0 : 加回成功，返回加回后的余量
--   -1   : 键不存在 → 不凭空创建（避免与未预热的 SKU 产生假余量），由调用方跳过
-- 说明：仅在键已存在时加回，保证「未预热降级放行」路径不会被回补操作污染。
-- =====================================================================
if redis.call('EXISTS', KEYS[1]) == 0 then
    return -1
end
return redis.call('INCRBY', KEYS[1], ARGV[1])
